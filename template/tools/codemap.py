"""Generate docs/CODEMAP.md: every source file and its top-level symbols.

This is the project's "memory graph". It is produced from the code, never written
by hand or by a model, so it cannot drift. CI runs it with ``--check`` and fails
when the committed map is stale; regenerate it with ``python tools/codemap.py``.

Top-level symbols only, found with simple per-language patterns. Standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

_PATTERNS: dict[str, re.Pattern[str]] = {
    ".py": re.compile(r"^(?:async\s+)?(class|def)\s+([A-Za-z]\w*)", re.MULTILINE),
    ".kt": re.compile(
        r"^(?:(?:public|internal|private|data|sealed|abstract|open|enum|annotation|value|inline|suspend|expect|actual)\s+)*"
        r"(class|interface|object|fun)\s+(?:<[^>]*>\s*)?(?:[\w.]+\.)?([A-Za-z]\w*)",
        re.MULTILINE,
    ),
    ".rs": re.compile(
        r"^pub(?:\([^)]*\))?\s+(?:async\s+)?(fn|struct|enum|trait|mod)\s+(\w+)", re.MULTILINE
    ),
    ".swift": re.compile(
        r"^(?:(?:public|internal|open|final)\s+)*(class|struct|enum|protocol|func|actor)\s+(\w+)",
        re.MULTILINE,
    ),
}
_SKIP_DIRS = {".git", "build", "target", ".gradle", "__pycache__", ".venv", "node_modules"}


@dataclass(frozen=True)
class Entry:
    path: str
    symbols: tuple[str, ...]


def scan(root: Path, roots: tuple[str, ...]) -> list[Entry]:
    entries: dict[str, Entry] = {}
    for top in roots:
        base = root / top
        if not base.is_dir():
            continue
        for file in sorted(base.rglob("*")):
            if not file.is_file() or file.suffix not in _PATTERNS:
                continue
            if _SKIP_DIRS.intersection(file.relative_to(root).parts):
                continue
            text = file.read_text(encoding="utf-8", errors="replace")
            symbols = tuple(f"{kind} {name}" for kind, name in _PATTERNS[file.suffix].findall(text))
            relative = file.relative_to(root).as_posix()
            entries[relative] = Entry(relative, symbols)
    return [entries[key] for key in sorted(entries)]


def render(entries: list[Entry]) -> str:
    lines = [
        "# Code map",
        "",
        "<!-- Generated by tools/codemap.py. Do not edit by hand. -->",
        "",
    ]
    if not entries:
        lines.append("_No source files yet._")
    for entry in entries:
        lines.append(
            f"- `{entry.path}`"
            + (": " + ", ".join(f"`{s}`" for s in entry.symbols) if entry.symbols else "")
        )
    return "\n".join(lines) + "\n"


def _default_roots() -> tuple[str, ...]:
    config = Path("guardrails.toml")
    if config.is_file():
        data = tomllib.loads(config.read_text(encoding="utf-8"))
        return tuple(data.get("codemap", {}).get("roots", ("src",)))
    return ("src",)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--roots", nargs="*", help="source folders to scan (default: guardrails.toml)"
    )
    parser.add_argument("--output", default="docs/CODEMAP.md")
    parser.add_argument("--check", action="store_true", help="fail if the committed map is stale")
    args = parser.parse_args(argv)

    roots = tuple(args.roots) if args.roots else _default_roots()
    content = render(scan(Path("."), roots))
    output = Path(args.output)
    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != content:
            print(
                f"::error::{output} is stale. Run 'python tools/codemap.py' and commit the result."
            )
            return 1
        print(f"{output} is up to date.")
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"Wrote {output}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
